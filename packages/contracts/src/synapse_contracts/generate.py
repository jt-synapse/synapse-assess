"""Export deterministic JSON Schema, OpenAPI and TypeScript declarations from Pydantic."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from pydantic.json_schema import models_json_schema

from . import models
from .catalog import openapi

PACKAGE = Path(__file__).resolve().parents[2]


def definitions(ref_template: str) -> dict[str, Any]:
    classes = sorted(
        (
            value
            for value in vars(models).values()
            if isinstance(value, type)
            and issubclass(value, models.Contract)
            and value is not models.Contract
        ),
        key=lambda value: value.__name__,
    )
    _, schema = models_json_schema(
        [(cls, "validation") for cls in classes], ref_template=ref_template
    )
    return schema["$defs"]


def ts_type(schema: dict[str, Any]) -> str:
    """Translate only schema constructs our Pydantic models use. Fail on unknown types."""
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(choice) for choice in schema["anyOf"])
    match schema.get("type"):
        case "string":
            return "string"
        case "number" | "integer":
            return "number"
        case "null":
            return "null"
        case "boolean":
            return "boolean"
        case "array":
            return "Array<" + ts_type(schema["items"]) + ">"
        case "object":
            if "properties" in schema:
                required = set(schema.get("required", []))
                fields = [
                    f"  {json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};"
                    for name, value in schema["properties"].items()
                ]
                return "{\n" + "\n".join(fields) + "\n}"
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                return "{ [key: string]: " + ts_type(extra) + " }"
            if extra is True:
                return "{ [key: string]: unknown }"
    raise ValueError(f"Unsupported schema for TypeScript export: {schema}")


def artifacts() -> dict[str, str]:
    defs = definitions("#/$defs/{model}")
    # Export every reachable type. AssessmentManifest is the root validator for manifest JSON files.
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$ref": "#/$defs/AssessmentManifest",
        "$defs": defs,
    }
    spec = openapi(definitions("#/components/schemas/{model}"))
    declarations = "// Generated by python -m synapse_contracts.generate.\n\n"
    declarations += "\n\n".join(
        f"export type {name} = {ts_type(value)};" for name, value in sorted(defs.items())
    )
    fixtures = json.loads((PACKAGE / "fixtures/shared.json").read_text())
    consumers = [
        "// Generated from fixtures/shared.json for a TypeScript consumer check.",
        'import type * as Contract from "./index";',
        "",
    ]
    for name, fixture in fixtures.items():
        model_name = fixture["type"]
        if model_name not in defs or not name.isidentifier():
            raise ValueError(f"Invalid fixture {name}")
        consumers.append(
            f"export const {name} = {json.dumps(fixture['value'], indent=2)} satisfies Contract.{model_name};"
        )
    return {
        "fixture-consumers.ts": "\n".join(consumers) + "\n",
        "schema.json": json.dumps(schema, indent=2) + "\n",
        "openapi.json": json.dumps(spec, indent=2) + "\n",
        "index.d.ts": declarations + "\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify exports without writing")
    args = parser.parse_args()
    directory = PACKAGE / "generated"
    for name, expected in artifacts().items():
        path = directory / name
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit(
                    f"Stale contract export: {name}. Run python -m synapse_contracts.generate"
                )
        else:
            directory.mkdir(exist_ok=True)
            path.write_text(expected)


if __name__ == "__main__":
    main()
